const (
	toolsJSONPath = "../../docs/tools.json"
	toolsMDPath   = "../../docs/tools.md"
	readmePath    = "../../README.md"
	serverJSON    = "../../server.json"
)

var updateDocs = flag.Bool("update", false, "rewrite docs/tools.json and docs/tools.md (make docs)")

// The docs are what a real client gets from the server, so they cannot describe a tool
// that does not exist or miss one that does.
func TestToolDocsMatchTheServer(t *testing.T) {
	h := start(t, labConfig(), labContext, passExec{})

	tools, err := h.session.ListTools(t.Context(), nil)
	require.NoError(t, err)

	raw, err := json.MarshalIndent(map[string]any{"tools": tools.Tools}, "", "  ")
	require.NoError(t, err)

	wantJSON := string(raw) + "\n"
	wantMD := renderTools(t, h.session.InitializeResult(), tools.Tools)

	if *updateDocs {
		require.NoError(t, os.WriteFile(toolsJSONPath, []byte(wantJSON), 0o600))
		require.NoError(t, os.WriteFile(toolsMDPath, []byte(wantMD), 0o600))
	}

	gotJSON, err := os.ReadFile(toolsJSONPath)
	require.NoError(t, err)
	gotMD, err := os.ReadFile(toolsMDPath)
	require.NoError(t, err)

	assert.Equal(t, wantJSON, string(gotJSON), "docs/tools.json is stale: run make docs")
	assert.Equal(t, wantMD, string(gotMD), "docs/tools.md is stale: run make docs")
}

func TestTheReadmeListsEveryTool(t *testing.T) {
	h := start(t, labConfig(), labContext, passExec{})

	tools, err := h.session.ListTools(t.Context(), nil)
	require.NoError(t, err)

	readme, err := os.ReadFile(readmePath)
	require.NoError(t, err)

	for _, tool := range tools.Tools {
		assert.Contains(t, string(readme), "| `"+tool.Name+"` |", "the README's tool table")
	}
}

func TestServerJSONNamesEverySetting(t *testing.T) {
	raw, err := os.ReadFile(serverJSON)
	require.NoError(t, err)

	var entry struct {
		Packages []struct {
			EnvironmentVariables []struct {
				Name string `json:"name"`
			} `json:"environmentVariables"`
		} `json:"packages"`
	}

	require.NoError(t, json.Unmarshal(raw, &entry))
	require.Len(t, entry.Packages, 1)

	var got []string
	for _, variable := range entry.Packages[0].EnvironmentVariables {
		got = append(got, variable.Name)
	}

	assert.ElementsMatch(t, []string{lab.EnvKubeconfig, lab.EnvAllowChanges, lab.EnvLabContext}, got)
}

func renderTools(t *testing.T, init *mcp.InitializeResult, tools []*mcp.Tool) string {
	t.Helper()

	var out strings.Builder

	fmt.Fprint(&out, "# Tools\n\n")
	fmt.Fprint(&out, "Generated by `make docs` from what the server returns over MCP, so do not edit it: a test\n"+
		"fails if it no longer matches the server. The `tools/list` result, as the protocol returns it, is\n"+
		"in [tools.json](tools.json).\n\n")
	fmt.Fprint(&out, "## Server\n\n")
	fmt.Fprint(&out, "| Field | Value |\n|---|---|\n")
	fmt.Fprintf(&out, "| Name | `%s` |\n", init.ServerInfo.Name)
	fmt.Fprint(&out, "| Transport | stdio |\n")
	fmt.Fprintf(&out, "| Protocol versions | %s |\n", codeList(mcp.SupportedProtocolVersions()))
	fmt.Fprintf(&out, "| Capabilities | %s |\n", codeList(capabilities(t, init)))
	fmt.Fprint(&out, "| Resources and prompts | none |\n\n")
	fmt.Fprintf(&out, "Instructions sent to the client:\n\n> %s\n\n", init.Instructions)

	fmt.Fprint(&out, "## What it can test\n\n")
	fmt.Fprint(&out, "| Scenario | What it does |\n|---|---|\n")

	scenarios := lab.Scenarios()
	for _, name := range slices.Sorted(maps.Keys(scenarios)) {
		fmt.Fprintf(&out, "| `%s` | %s |\n", name, scenarios[name])
	}

	fmt.Fprint(&out, "\n## Summary\n\n")
	fmt.Fprint(&out, "| Tool | Title | Changes the lab |\n|---|---|---|\n")

	for _, tool := range tools {
		fmt.Fprintf(&out, "| [`%s`](#%s) | %s | %s |\n", tool.Name, tool.Name, tool.Title, yesNo(!tool.Annotations.ReadOnlyHint))
	}

	for _, tool := range tools {
		renderTool(&out, tool)
	}

	return out.String()
}

func renderTool(out *strings.Builder, tool *mcp.Tool) {
	fmt.Fprintf(out, "\n## %s\n\n**%s.** %s\n\n", tool.Name, tool.Title, tool.Description)
	fmt.Fprintf(out, "Annotations: `readOnlyHint` %t, `destructiveHint` %t, `openWorldHint` %t.\n\n",
		tool.Annotations.ReadOnlyHint, *tool.Annotations.DestructiveHint, *tool.Annotations.OpenWorldHint)

	input := asObject(tool.InputSchema)
	properties := asObject(input["properties"])

	fmt.Fprint(out, "### Input\n\n")

	if len(properties) == 0 {
		fmt.Fprint(out, "None. Unknown fields are refused.\n\n")
	} else {
		fmt.Fprint(out, "Unknown fields are refused.\n\n")
		fmt.Fprint(out, "| Field | Type | Required | Allowed | Description |\n|---|---|---|---|---|\n")

		for _, name := range slices.Sorted(maps.Keys(properties)) {
			property := asObject(properties[name])
			fmt.Fprintf(out, "| `%s` | %s | %s | %s | %s |\n", name, typeOf(property),
				yesNo(slices.Contains(asStrings(input["required"]), name)), allowed(property), property["description"])
		}

		fmt.Fprintln(out)
	}

	fmt.Fprint(out, "### Output\n\n")

	output := asObject(tool.OutputSchema)
	fields := asObject(output["properties"])

	if len(fields) == 0 {
		fmt.Fprintf(out, "%s. Full schema in [tools.json](tools.json).\n", typeOf(output))
		return
	}

	fmt.Fprint(out, "Top-level fields; full schema in [tools.json](tools.json).\n\n")
	fmt.Fprint(out, "| Field | Type |\n|---|---|\n")

	for _, name := range slices.Sorted(maps.Keys(fields)) {
		fmt.Fprintf(out, "| `%s` | %s |\n", name, typeOf(asObject(fields[name])))
	}
}

func capabilities(t *testing.T, init *mcp.InitializeResult) []string {
	t.Helper()

	raw, err := json.Marshal(init.Capabilities)
	require.NoError(t, err)

	var fields map[string]any
	require.NoError(t, json.Unmarshal(raw, &fields))

	return slices.Sorted(maps.Keys(fields))
}

func typeOf(schema map[string]any) string {
	names := asStrings(schema["type"])
	if name, ok := schema["type"].(string); ok {
		names = []string{name}
	}

	names = slices.DeleteFunc(names, func(name string) bool { return name == "null" })
	if len(names) == 0 {
		return "any"
	}

	switch names[0] {
	case "array":
		return "array of " + typeOf(asObject(schema["items"]))
	case "object":
		if values := asObject(schema["additionalProperties"]); values != nil && asObject(schema["properties"]) == nil {
			return "object of " + typeOf(values)
		}
	}

	return names[0]
}

func allowed(property map[string]any) string {
	if values, ok := property["enum"].([]any); ok {
		parts := make([]string, 0, len(values))
		for _, value := range values {
			parts = append(parts, fmt.Sprintf("`%v`", value))
		}

		return strings.Join(parts, ", ")
	}

	if property["minimum"] != nil && property["maximum"] != nil {
		return fmt.Sprintf("%v to %v", property["minimum"], property["maximum"])
	}

	return "any"
}

func asObject(value any) map[string]any {
	object, _ := value.(map[string]any)
	return object
}

func asStrings(value any) []string {
	values, _ := value.([]any)

	out := make([]string, 0, len(values))
	for _, item := range values {
		out = append(out, fmt.Sprint(item))
	}

	return out
}

func codeList(values []string) string {
	parts := make([]string, 0, len(values))
	for _, value := range values {
		parts = append(parts, "`"+value+"`")
	}

	return strings.Join(parts, ", ")
}

func yesNo(value bool) string {
	if value {
		return "yes"
	}

	return "no"
}
